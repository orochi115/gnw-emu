#!/usr/bin/env python3
"""Generate kernels.S: timing kernels for the Cortex-M7 bench.

Every kernel has the C signature
    void k_NAME(uint32_t iters, uint32_t a1, uint32_t a2, uint32_t a3);
and runs `iters` iterations of an unrolled body of REPS copies.  The C side
reads DWT_CYCCNT around the call; parse.py subtracts the cost of the "empty"
kernel (same loop, no body) and divides by iters*REPS.

All kernels are position independent (no literal pools, only relative
branches), so the C side can copy them to ITCM / AXI / AHB / SRD SRAM and
call the copy to measure instruction fetch from that memory.  The symbol
k_NAME_end marks the end of each kernel.

Registers: r12 = iteration counter, r1..r3 = arguments.  Streaming kernels
use r0 = buffer base and lr = base + span (a2) and wrap r1 back to the base
at the top of every iteration.
"""
import sys

WRAP = ["cmp r1, lr", "it hs", "movhs r1, r0"]
STREAM_SETUP = ["mov r0, r1", "add lr, r1, r2"]
FP_SETUP = ["movs r4, #0", "vmov s1, r4", "vmov.f32 s0, #1.0", "vmov.f32 s2, #1.0",
            "vmov.f64 d2, #1.0", "vmov s6, r4", "vmov s7, r4"]
FP64_SETUP = FP_SETUP + ["vmov.f64 d0, #1.0"]

# name: (setup, per-iteration prologue, body cycle, reps)
# The body cycle is repeated round-robin until REPS instructions (lines) are emitted;
# "ops" per rep is given separately where one rep spans several lines.
KERNELS = {
    "empty":      ([], [], [], 0),
    "nop":        ([], [], ["nop"], 64),
    "add_dep":    (["movs r4, #1", "movs r5, #3"], [], ["add r4, r5"], 64),
    "add_indep":  (["movs r4, #1", "movs r5, #3"], [],
                   ["add r4, r5", "add r6, r5", "add r7, r5", "add r8, r5"], 64),
    "addw_indep": (["movs r4, #1", "movs r5, #3"], [],
                   ["add.w r4, r4, r5", "add.w r6, r6, r5", "add.w r7, r7, r5",
                    "add.w r8, r8, r5"], 64),
    "mul_dep":    (["movs r4, #1", "movs r5, #3"], [], ["mul r4, r4, r5"], 64),
    "mul_indep":  (["movs r4, #1", "movs r5, #3"], [],
                   ["mul r4, r4, r5", "mul r6, r6, r5", "mul r7, r7, r5",
                    "mul r8, r8, r5"], 64),
    "mla_dep":    (["movs r4, #1", "movs r5, #3", "movs r6, #7"], [],
                   ["mla r4, r4, r5, r6"], 64),
    # Divider operands come from a2 (dividend) and a3 (divisor).
    "udiv":       ([], [], ["udiv r4, r2, r3"], 64),
    "sdiv":       ([], [], ["sdiv r4, r2, r3"], 64),
    "b_taken":    ([], [], ["b 2f", "2:"], 64),
    "vadd_dep":   (FP_SETUP, [], ["vadd.f32 s0, s0, s1"], 64),
    "vmul_dep":   (FP_SETUP, [], ["vmul.f32 s0, s0, s2"], 64),
    "vfma_dep":   (FP_SETUP, [], ["vfma.f32 s0, s2, s1"], 64),
    "vdiv_dep":   (FP_SETUP, [], ["vdiv.f32 s0, s0, s2"], 32),
    "vsqrt_dep":  (FP_SETUP, [], ["vsqrt.f32 s0, s0"], 32),
    "vadd64_dep": (FP64_SETUP, [], ["vadd.f64 d0, d0, d3"], 64),
    "vdiv64_dep": (FP64_SETUP, [], ["vdiv.f64 d0, d0, d2"], 32),
    "vsqrt64_dep": (FP64_SETUP, [], ["vsqrt.f64 d0, d0"], 32),
    # Memory.  a1 = buffer, a2 = span in bytes (streaming kernels).
    # ld_lat: load-to-use latency + 2 ALU ops (alu2_lat measures the ALU part).
    "ld_lat":     ([], [], ["ldr r4, [r1]", "eor r1, r1, r4", "eor r1, r1, r4"], 32),
    "alu2_lat":   (["movs r4, #0"], [], ["eor r1, r1, r4", "eor r1, r1, r4"], 32),
    "ld_tput":    ([], [], [f"ldr r{4 + i % 8}, [r1, #{4 * i}]" for i in range(8)], 64),
    "ld_seq":     (STREAM_SETUP, WRAP, ["ldr r4, [r1], #4"], 64),
    "ld_line":    (STREAM_SETUP, WRAP, ["ldr r4, [r1], #32"], 64),
    "ld_lat_line": (STREAM_SETUP, WRAP,
                    ["ldr r4, [r1], #32", "eor r1, r1, r4", "eor r1, r1, r4"], 32),
    "ldm_seq":    (STREAM_SETUP, WRAP, ["ldmia r1!, {r2-r9}"], 16),
    "st_seq":     (STREAM_SETUP, WRAP, ["str r4, [r1], #4"], 64),
    "st_same":    ([], [], ["str r4, [r1]"], 64),
    # Instruction fetch: long straight-line bodies (2 KiB / 4 KiB).
    "fetch_nop":  ([], [], ["nop"], 1024),
    "fetch_addw": (["movs r4, #1", "movs r5, #3"], [],
                   ["add.w r4, r4, r5", "add.w r6, r6, r5", "add.w r7, r7, r5",
                    "add.w r8, r8, r5"], 1024),
}

# Lines per rep for kernels whose body cycle is one logical op of several lines.
GROUPED = {"b_taken", "ld_lat", "alu2_lat", "ld_lat_line"}


def body_lines(name, cycle, reps):
    if not reps:
        return []
    if name in GROUPED:
        return cycle * reps
    return [cycle[i % len(cycle)] for i in range(reps)]


def emit(out):
    w = out.write
    w("/* Generated by gen_kernels.py; do not edit. */\n")
    w("\t.syntax unified\n\t.cpu cortex-m7\n\t.fpu fpv5-d16\n\t.thumb\n")
    w("\t.section .kernels, \"ax\", %progbits\n")
    for name, (setup, pre, cycle, reps) in KERNELS.items():
        sym = f"k_{name}"
        w(f"\n\t.p2align 5\n\t.global {sym}\n\t.global {sym}_end\n")
        w(f"\t.type {sym}, %function\n\t.thumb_func\n{sym}:\n")
        w("\tpush {r4-r11, lr}\n\tmov r12, r0\n")
        for line in setup:
            w(f"\t{line}\n")
        w("1:\n")
        for line in pre:
            w(f"\t{line}\n")
        for line in body_lines(name, cycle, reps):
            w(f"\t{line}\n")
        w("\tsubs r12, r12, #1\n\tbne 1b\n\tpop {r4-r11, pc}\n")
        w(f"{sym}_end:\n\t.size {sym}, {sym}_end - {sym}\n")


def emit_header(out):
    w = out.write
    w("/* Generated by gen_kernels.py; do not edit. */\n#include <stdint.h>\n")
    w("typedef void (*kern_t)(uint32_t iters, uint32_t a1, uint32_t a2, uint32_t a3);\n")
    for name, (_, _, _, reps) in KERNELS.items():
        w(f"void k_{name}(uint32_t, uint32_t, uint32_t, uint32_t);\n")
        w(f"extern char k_{name}_end[];\n#define K_{name}_REPS {reps}\n")


if __name__ == "__main__":
    with open(sys.argv[1], "w") as f:
        emit(f)
    with open(sys.argv[2], "w") as f:
        emit_header(f)
